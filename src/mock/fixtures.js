/**
 * Look up a fixture entry.
 * @param {string} agent_id
 * @param {number} step
 * @returns {Object} fixture entry
 * @throws {import('../models.js').MissingFixtureError}
 */
export function getFixture(agent_id, step) {
  const key = `${agent_id}:${step}`;
  const entry = FIXTURES[key];
  if (!entry) {
    // Import inline to avoid circular dependency at module load time
    const { MissingFixtureError } = await_import_models();
    throw new MissingFixtureError(agent_id, step);
  }
  return entry;
}

// Synchronous workaround for the circular import concern: MissingFixtureError
// is a plain class with no dependencies, so we just define a local shim here.
function await_import_models() {
  // This is only called in the error path, so the synchronous shim is fine.
  class MissingFixtureError extends Error {
    constructor(agent_id, step) {
      super(`No fixture for agent "${agent_id}" step ${step}`);
      this.name = 'MissingFixtureError';
      this.agent_id = agent_id;
      this.step = step;
    }
  }
  return { MissingFixtureError };
}
